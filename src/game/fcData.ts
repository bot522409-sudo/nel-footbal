export interface FcPlayerStats {
  pac: number;
  sho: number;
  pas: number;
  dri: number;
  def: number;
  phy: number;
}

export interface FcPlayerCard {
  id: string;
  name: string;
  shortName: string;
  ovr: number;
  /** True for Admin Infinity (∞) legends; numeric ovr stays <= 200 for cloud save compatibility */
  isInfinity?: boolean;
  position: PlayerPosition;
  rarity: CardRarity;
  numberStr: string;
  foot: 'right' | 'left';
  nation: string;
  club: string;
  stats: FcPlayerStats;
  jerseyColor: string;
  shortsColor: number;
  skinColor: number;
  hairColor: number;
  bootColor: number;
  hasBeard?: boolean;
  /** Optional link to FreeKickEngine kicker profile */
  kickerId?: KickerId;
  /** Optional link to FreeKickEngine GK profile */
  gkId?: GoalkeeperId;
}

export interface FcPackTierOdds {
  labelVi: string;
  labelEn: string;
  minOvr: number;
  maxOvr: number;
  chancePct: number;
  isRare130Plus?: boolean;
  rarities?: CardRarity[];
  positions?: PlayerPosition[];
  nations?: string[];
  kickerIds?: KickerId[];
}

export interface FcPackDef {
  id: FcPackId;
  nameVi: string;
  nameEn: string;
  descVi: string;
  descEn: string;
  price: number;
  cardsCount: number;
  minOvr: number;
  maxOvr: number;
  accentColor: string;
  badgeText: string;
  adminOnly?: boolean;
  tierOdds: FcPackTierOdds[];
}

export type MissionPeriod = 'daily' | 'weekly';

export type MissionDifficulty = 'easy' | 'medium' | 'hard' | 'extreme';

export type MissionMetric =
  | 'goals'
  | 'top_corner'
  | 'matches_won'
  | 'match_3d_won'
  | 'hard_matches_won'
  | 'gk_saves'
  | 'header_or_penalty'
  | 'packs_opened';

export interface FcMissionDef {
  id: string;
  period: MissionPeriod;
  difficulty: MissionDifficulty;
  metric: MissionMetric;
  target: number;
  rewardCoins: number;
  titleVi: string;
  titleEn: string;
  descVi: string;
  descEn: string;
}

export interface FcMissionProgressState {
  dailyDate: string;
  weeklyKey: string;
  dailyProgress: Record<string, number>;
  dailyClaimed: string[];
  weeklyProgress: Record<string, number>;
  weeklyClaimed: string[];
}

export interface FcClubState {
  coins: number;
  ownedIds: string[];
  /** 5-slot active 3D Match lineup: [GK, CB, CM, LW/RW, ST] */
  lineupIds: [string, string, string, string, string];
  /** Selected Free Kick / Penalty taker card ID */
  activeKickerCardId: string;
  /** Selected Goalkeeper card ID */
  activeGkCardId: string;
  packsOpened: number;
  missions: FcMissionProgressState;
}

