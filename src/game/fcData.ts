export function createFreshMissionsState(now = new Date()): FcMissionProgressState {
  return {
    dailyDate: getTodayDateKey(now),
    weeklyKey: getIsoWeekKey(now),
    dailyProgress: {},
    dailyClaimed: [],
    weeklyProgress: {},
    weeklyClaimed: [],
  };
}

export function ensureFreshMissions(
  missions?: Partial<FcMissionProgressState>,
  now = new Date(),
): FcMissionProgressState {
  const today = getTodayDateKey(now);
  const week = getIsoWeekKey(now);
  const sameDay = missions?.dailyDate === today;
  const sameWeek = missions?.weeklyKey === week;

  return {
    dailyDate: today,
    weeklyKey: week,
    dailyProgress: sameDay && missions?.dailyProgress ? { ...missions.dailyProgress } : {},
    dailyClaimed: sameDay && Array.isArray(missions?.dailyClaimed) ? [...missions.dailyClaimed] : [],
    weeklyProgress: sameWeek && missions?.weeklyProgress ? { ...missions.weeklyProgress } : {},
    weeklyClaimed: sameWeek && Array.isArray(missions?.weeklyClaimed) ? [...missions.weeklyClaimed] : [],
  };
}

export function applyMissionEvent(
  state: FcClubState,
  deltas: Partial<Record<MissionMetric, number>>,
): FcClubState {
  const missions = ensureFreshMissions(state.missions);
  let changed = false;

  for (const m of FC_MISSIONS) {
    const inc = deltas[m.metric];
    if (!inc || inc <= 0) continue;
    changed = true;
    if (m.period === 'daily') {
      const cur = missions.dailyProgress[m.id] ?? 0;
      missions.dailyProgress[m.id] = Math.min(m.target, cur + inc);
    } else {
      const cur = missions.weeklyProgress[m.id] ?? 0;
      missions.weeklyProgress[m.id] = Math.min(m.target, cur + inc);
    }
  }

  if (!changed && missions.dailyDate === state.missions.dailyDate && missions.weeklyKey === state.missions.weeklyKey) {
    return state;
  }

  return { ...state, missions };
}

export function getMissionProgressValue(
  missions: FcMissionProgressState,
  mission: FcMissionDef,
): { progress: number; claimed: boolean; claimable: boolean } {
  const progress =
    mission.period === 'daily'
      ? missions.dailyProgress[mission.id] ?? 0
      : missions.weeklyProgress[mission.id] ?? 0;
  const claimed =
    mission.period === 'daily'
      ? missions.dailyClaimed.includes(mission.id)
      : missions.weeklyClaimed.includes(mission.id);
  const claimable = !claimed && progress >= mission.target;
  return { progress: Math.min(mission.target, progress), claimed, claimable };
}

export function countClaimableMissions(state: FcClubState): number {
  const fresh = ensureFreshMissions(state.missions);
  let count = 0;
  for (const m of FC_MISSIONS) {
    if (getMissionProgressValue(fresh, m).claimable) count += 1;
  }
  return count;
}

export function claimMissionReward(
  state: FcClubState,
  missionId: string,
): FcClubState {
  const mission = FC_MISSIONS.find((m) => m.id === missionId);
  if (!mission) return state;
  const missions = ensureFreshMissions(state.missions);
  const { claimable } = getMissionProgressValue(missions, mission);
  if (!claimable) return state;

  if (mission.period === 'daily') {
    missions.dailyClaimed = [...missions.dailyClaimed, mission.id];
  } else {
    missions.weeklyClaimed = [...missions.weeklyClaimed, mission.id];
  }

  return {
    ...state,
    coins: state.coins + mission.rewardCoins,
    missions,
  };
}

export function claimAllMissionRewards(state: FcClubState): {
  nextState: FcClubState;
  totalClaimedCoins: number;
  claimedCount: number;
} {
  let nextState = { ...state, missions: ensureFreshMissions(state.missions) };
  let totalClaimedCoins = 0;
  let claimedCount = 0;

  for (const m of FC_MISSIONS) {
    const before = nextState.coins;
    nextState = claimMissionReward(nextState, m.id);
    if (nextState.coins > before) {
      totalClaimedCoins += nextState.coins - before;
      claimedCount += 1;
    }
  }

  return { nextState, totalClaimedCoins, claimedCount };
}

